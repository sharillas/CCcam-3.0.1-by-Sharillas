static int via3_decrypt(const uint8_t *source, uint8_t *dw, uint32_t ident, uint8_t desKeyIndex,
						uint8_t aesKeyIndex, uint8_t aesMode, int doFinalMix)
{
	int aesAfterCore = 0, needsAES = (aesKeyIndex != 0xFF);
	int32_t i, j;

	uint8_t tmpData[8], C1[8];
	uint8_t *pXorVector;

	char aesKey[16];

	if (ident == 0)
	{
		return CCCAM_EMU_CORRUPT_DATA;
	}

	if (!via_get_key(C1, ident, 'C', 1, 8))
	{
		return CCCAM_EMU_KEY_NOT_FOUND;
	}

	if (needsAES && !via_get_key((uint8_t *)aesKey, ident, 'E', aesKeyIndex, 16))
	{
		return CCCAM_EMU_KEY_NOT_FOUND;
	}

	if (aesMode == 0x0D || aesMode == 0x11 || aesMode == 0x15)
	{
		aesAfterCore = 1;
	}

	if (needsAES && !aesAfterCore)
	{
		if (aesMode == 0x0F)
		{
			hdSurEncPhase1_D2_0F_11((uint8_t *)source);
			hdSurEncPhase2_D2_0F_11((uint8_t *)source);
		}
		else if (aesMode == 0x13)
		{
			hdSurEncPhase1_D2_13_15((uint8_t *)source);
		}

		cccam_emu_aes_decrypt_block((uint8_t *)source, (uint8_t *)aesKey);

		if (aesMode == 0x0F)
		{
			hdSurEncPhase1_D2_0F_11((uint8_t *)source);
		}
		else if (aesMode == 0x13)
		{
			hdSurEncPhase2_D2_13_15((uint8_t *)source);
		}
	}

	for (i = 0; i < 2; i++)
	{
		memcpy(tmpData, source + i * 8, 8);
		via3_process_dw(tmpData, ident, desKeyIndex);

		if (i != 0)
		{
			pXorVector = (uint8_t *)source;
		}
		else
		{
			pXorVector = &C1[0];
		}

		for (j = 0; j < 8; j++)
		{
			dw[i * 8 + j] = tmpData[j] ^ pXorVector[j];
		}
	}

	if (needsAES && aesAfterCore)
	{
		if (aesMode == 0x11)
		{
			hdSurEncPhase1_D2_0F_11(dw);
			hdSurEncPhase2_D2_0F_11(dw);
		}
		else if (aesMode == 0x15)
		{
			hdSurEncPhase1_D2_13_15(dw);
		}

		cccam_emu_aes_decrypt_block(dw, (uint8_t *)aesKey);

		if (aesMode == 0x11)
		{
			hdSurEncPhase1_D2_0F_11(dw);
		}

		if (aesMode == 0x15)
		{
			hdSurEncPhase2_D2_13_15(dw);
		}
	}

	if (ident == 0x030B00)
	{
		if (doFinalMix)
		{
			via3_final_mix(dw);
		}

		if (!cccam_emu_is_valid_dcw(dw) || !cccam_emu_is_valid_dcw(dw + 8))
		{
			return CCCAM_EMU_CHECKSUM_ERROR;
		}
	}

	return CCCAM_EMU_OK;
}

