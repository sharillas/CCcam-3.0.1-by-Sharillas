int cccam_emu_viaccess_ecm(const uint8_t *ecm, uint16_t ecm_len, uint8_t *dw)
{
	int doFinalMix = 0;

	uint8_t nanoCmd = 0, nanoLen = 0, version = 0, providerKeyLen = 0;
	uint8_t desKeyIndex = 0, aesMode = 0, aesKeyIndex = 0xFF;
	uint16_t i = 0, keySelectPos = 0;
	uint32_t currentIdent = 0;

	if (!ecm || !dw || ecm_len < 4) {
		return CCCAM_EMU_CORRUPT_DATA;
	}

	for (i = 4; i + 2 < ecm_len; )
	{
		nanoCmd = ecm[i++];
		nanoLen = ecm[i++];

		if (i + nanoLen > ecm_len)
		{
			return CCCAM_EMU_NOT_SUPPORTED;
		}

		switch (nanoCmd)
		{
			case 0x40:
				if (nanoLen < 0x03)
				{
					break;
				}
				version = ecm[i];
				if (nanoLen == 3)
				{
					currentIdent = ((ecm[i] << 16) | (ecm[i + 1] << 8)) | (ecm[i + 2] & 0xF0);
					desKeyIndex = ecm[i + 2] & 0x0F;
					keySelectPos = i + 3;
				}
				else
				{
					currentIdent = (ecm[i] << 16) | (ecm[i + 1] << 8) | ((ecm[i + 2] >> 4) & 0x0F);
					desKeyIndex = ecm[i + 3];
					keySelectPos = i + 4;
				}
				providerKeyLen = nanoLen;
				break;

			case 0x90:
				if (nanoLen < 0x03)
				{
					break;
				}
				version = ecm[i];
				currentIdent = ((ecm[i] << 16) | (ecm[i + 1] << 8)) | (ecm[i + 2] & 0xF0);
				desKeyIndex = ecm[i + 2] & 0x0F;
				keySelectPos = i + 4;
				if ((version == 3) && (nanoLen > 3))
				{
					desKeyIndex = ecm[i + (nanoLen - 4)] & 0x0F;
				}
				providerKeyLen = nanoLen;
				break;

			case 0x80:
				nanoLen = 0;
				break;

			case 0xD2:
				if (nanoLen < 0x02)
				{
					break;
				}
				aesMode = ecm[i];
				aesKeyIndex = ecm[i + 1];
				break;

			case 0xDD:
				nanoLen = 0;
				break;

			case 0xEA:
				if (nanoLen < 0x10)
				{
					break;
				}
				if (version < 2)
				{
					return via1_decrypt_ex(ecm, ecm_len, dw, currentIdent, desKeyIndex);
				}
				else if (version == 2)
				{
					return via26_decrypt(ecm + i, dw, currentIdent, desKeyIndex);
				}
				else if (version == 3)
				{
					doFinalMix = 0;
					if (currentIdent == 0x030B00 && providerKeyLen > 3)
					{
						if (keySelectPos + 2 >= ecm_len)
						{
							break;
						}
						if (ecm[keySelectPos] == 0x05 && ecm[keySelectPos + 1] == 0x67 &&
							(ecm[keySelectPos + 2] == 0x00 || ecm[keySelectPos + 2] == 0x01))
						{
							if (ecm[keySelectPos + 2] == 0x01)
							{
								doFinalMix = 1;
							}
						}
						else
						{
							break;
						}
					}

					return via3_decrypt(ecm + i, dw, currentIdent, desKeyIndex, aesKeyIndex, aesMode, doFinalMix);
				}
				break;

			default:
				break;
		}

		i += nanoLen;
	}

	return CCCAM_EMU_NOT_SUPPORTED;
}

