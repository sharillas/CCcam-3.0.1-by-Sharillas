static int via26_process_dw(uint8_t *indata, uint32_t ident, uint8_t desKeyIndex)
{
	uint8_t pv1, pv2, i;
	uint8_t Tmp[8], T1Key[300], P1Key[8], KeyDes1[16], KeyDes2[16], XorKey[8];
	uint32_t ks1[32], ks2[32];

	if (!via_get_key(T1Key, ident, 'T', 1, 300)) return 2;
	if (!via_get_key(P1Key, ident, 'P', 1, 8)) return 2;
	if (!via_get_key(KeyDes1, ident, 'D', 1, 16)) return 2;
	if (!via_get_key(KeyDes2, ident, '0', desKeyIndex, 16)) return 2;
	if (!via_get_key(XorKey, ident, 'X', 1, 8)) return 2;

	for (i = 0; i < 8; i++)
	{
		pv1 = indata[i];
		Tmp[i] = T1Key[pv1];
	}

	for (i = 0; i < 8; i++)
	{
		pv1 = P1Key[i];
		pv2 = Tmp[pv1];
		indata[i] = pv2;
	}

	cccam_emu_des_set_key(KeyDes1, ks1);
	cccam_emu_des(indata, ks1, 1);

	for (i = 0; i < 8; i++)
	{
		indata[i] ^= XorKey[i];
	}

	cccam_emu_des_set_key(KeyDes2, ks1);
	cccam_emu_des_set_key(KeyDes2 + 8, ks2);
	cccam_emu_des(indata, ks1, 0);
	cccam_emu_des(indata, ks2, 1);
	cccam_emu_des(indata, ks1, 0);

	for (i = 0; i < 8; i++)
	{
		indata[i] ^= XorKey[i];
	}

	cccam_emu_des_set_key(KeyDes1, ks1);
	cccam_emu_des(indata, ks1, 0);

	for (i = 0; i < 8; i++)
	{
		pv1 = indata[i];
		pv2 = P1Key[i];
		Tmp[pv2] = pv1;
	}

	for (i = 0; i < 8; i++)
	{
		pv1 = Tmp[i];
		pv2 = T1Key[pv1];
		indata[i] = pv2;
	}

	return 0;
}

static int via26_decrypt(const uint8_t *source, uint8_t *dw, uint32_t ident, uint8_t desKeyIndex)
{
	uint8_t tmpData[8], C1[8];
	uint8_t *pXorVector;
	int32_t i, j;

	if (ident == 0)
	{
		return CCCAM_EMU_CORRUPT_DATA;
	}

	if (!via_get_key(C1, ident, 'C', 1, 8))
	{
		return CCCAM_EMU_KEY_NOT_FOUND;
	}

	for (i = 0; i < 2; i++)
	{
		memcpy(tmpData, source + i * 8, 8);
		via26_process_dw(tmpData, ident, desKeyIndex);

		if (i != 0)
		{
			pXorVector = (uint8_t *)source;
		}
		else
		{
			pXorVector = &C1[0];
		}

		for (j = 0; j < 8; j++)
		{
			dw[i * 8 + j] = tmpData[j] ^ pXorVector[j];
		}

		// Fix CW checksum bytes
		for (j = 3; j < 8; j += 4)
		{
			dw[i * 8 + j] = (dw[i * 8 + j - 3] + dw[i * 8 + j - 2] + dw[i * 8 + j - 1]) & 0xFF;
		}
	}

	return CCCAM_EMU_OK;
}

