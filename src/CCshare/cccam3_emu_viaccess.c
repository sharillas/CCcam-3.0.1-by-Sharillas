static void via3_core(uint8_t *data, uint8_t Off, uint32_t ident, uint8_t *XorKey, uint8_t *T1Key)
{
	uint8_t i;
	uint32_t lR2, lR3, lR4, lR6, lR7;

	switch (ident)
	{
		case 0x032820:
		{
			for (i = 0; i < 4; i++)
			{
				data[i] ^= XorKey[(Off + i) & 0x07];
			}

			lR2 = (data[0] ^ 0xBD) + data[0];
			lR3 = (data[3] ^ 0xEB) + data[3];
			lR2 = (lR2 - lR3) ^ data[2];
			lR3 = ((0x39 * data[1]) << 2);
			data[4] = (lR2 | lR3) + data[2];

			lR3 = ((((data[0] + 6) ^ data[0]) | (data[2] << 1)) ^ 0x65) + data[0];
			lR2 = (data[1] ^ 0xED) + data[1];
			lR7 = ((data[3] + 0x29) ^ data[3]) * lR2;
			data[5] = lR7 + lR3;

			lR2 = ((data[2] ^ 0x33) + data[2]) & 0x0A;
			lR3 = (data[0] + 0xAD) ^ data[0];
			lR3 = lR3 + lR2;
			lR2 = data[3] * data[3];
			lR7 = (lR2 | 1) + data[1];
			data[6] = (lR3 | lR7) + data[1];

			lR3 = data[1] & 0x07;
			lR2 = (lR3 - data[2]) & (data[0] | lR2 | 0x01);
			data[7] = lR2 + data[3];

			for (i = 0; i < 4; i++)
			{
				data[i + 4] = T1Key[data[i + 4]];
			}
		}
		break;

		case 0x030B00:
		{
			for (i = 0; i < 4; i++)
			{
				data[i] ^= XorKey[(Off + i) & 0x07];
			}

			lR6 = (data[3] + 0x6E) ^ data[3];
			lR6 = (lR6 * (data[2] << 1)) + 0x17;
			lR3 = (data[1] + 0x77) ^ data[1];
			lR4 = (data[0] + 0xD7) ^ data[0];
			data[4] = ((lR4 & lR3) | lR6) + data[0];

			lR4 = ((data[3] + 0x71) ^ data[3]) ^ 0x90;
			lR6 = (data[1] + 0x1B) ^ data[1];
			lR4 = (lR4 * lR6) ^ data[0];
			data[5] = (lR4 ^ (data[2] << 1)) + data[1];

			lR3 = (data[3] * data[3]) | 0x01;
			lR4 = (((data[2] ^ 0x35) + data[2]) | lR3) + data[2];
			lR6 = data[1] ^ (data[0] + 0x4A);
			data[6] = lR6 + lR4;

			lR3 = (data[0] * (data[2] << 1)) | data[1];
			lR4 = 0xFE - data[3];
			lR3 = lR4 ^ lR3;
			data[7] = lR3 + data[3];

			for (i = 0; i < 4; i++)
			{
				data[4 + i] = T1Key[data[4 + i]];
			}
		}
		break;

		default:
			break;
	}
}

static void via3_fct1(uint8_t *data, uint32_t ident, uint8_t *XorKey, uint8_t *T1Key)
{
	uint8_t t;

	via3_core(data, 0, ident, XorKey, T1Key);

	switch (ident)
	{
		case 0x032820:
		{
			t = data[4];
			data[4] = data[7];
			data[7] = t;
		}
		break;

		case 0x030B00:
		{
			t = data[5];
			data[5] = data[7];
			data[7] = t;
		}
		break;

		default:
			break;
	}
}

static void via3_fct2(uint8_t *data, uint32_t ident, uint8_t *XorKey, uint8_t *T1Key)
{
	uint8_t t;

	via3_core(data, 4, ident, XorKey, T1Key);

	switch (ident)
	{
		case 0x032820:
		{
			t = data[4];
			data[4] = data[7];
			data[7] = data[5];
			data[5] = data[6];
			data[6] = t;
		}
		break;

		case 0x030B00:
		{
			t = data[6];
			data[6] = data[7];
			data[7] = t;
		}
		break;

		default:
			break;
	}
}

static int via3_process_dw(uint8_t *data, uint32_t ident, uint8_t desKeyIndex)
{
	uint8_t i;
	uint8_t tmp[8], T1Key[300], P1Key[8], KeyDes[16], XorKey[8];
	uint32_t ks1[32], ks2[32];

	if (!via_get_key(T1Key, ident, 'T', 1, 300)) return 2;
	if (!via_get_key(P1Key, ident, 'P', 1, 8)) return 2;
	if (!via_get_key(KeyDes, ident, '0', desKeyIndex, 16)) return 2;
	if (!via_get_key(XorKey, ident, 'X', 1, 8)) return 2;

	for (i = 0; i < 4; i++)
	{
		tmp[i] = data[i + 4];
	}

	via3_fct1(tmp, ident, XorKey, T1Key);

	for (i = 0; i < 4; i++)
	{
		tmp[i] = data[i] ^ tmp[i + 4];
	}

	via3_fct2(tmp, ident, XorKey, T1Key);

	for (i = 0; i < 4; i++)
	{
		tmp[i] ^= XorKey[i + 4];
	}

	for (i = 0; i < 4; i++)
	{
		data[i] = data[i + 4] ^ tmp[i + 4];
		data[i + 4] = tmp[i];
	}

	cccam_emu_des_set_key(KeyDes, ks1);
	cccam_emu_des_set_key(KeyDes + 8, ks2);

	cccam_emu_des(data, ks1, 0);
	cccam_emu_des(data, ks2, 1);
	cccam_emu_des(data, ks1, 0);

	for (i = 0; i < 4; i++)
	{
		tmp[i] = data[i + 4];
	}

	via3_fct2(tmp, ident, XorKey, T1Key);

	for (i = 0; i < 4; i++)
	{
		tmp[i] = data[i] ^ tmp[i + 4];
	}

	via3_fct1(tmp, ident, XorKey, T1Key);

	for (i = 0; i < 4; i++)
	{
		tmp[i] ^= XorKey[i];
	}

	for (i = 0; i < 4; i++)
	{
		data[i] = data[i + 4] ^ tmp[i + 4];
		data[i + 4] = tmp[i];
	}

	return 0;
}

static void via3_final_mix(uint8_t *dw)
{
	uint8_t tmp[4];

	memcpy(tmp, dw, 4);
	memcpy(dw, dw + 4, 4);
	memcpy(dw + 4, tmp, 4);

	memcpy(tmp, dw + 8, 4);
	memcpy(dw + 8, dw + 12, 4);
	memcpy(dw + 12, tmp, 4);
}

