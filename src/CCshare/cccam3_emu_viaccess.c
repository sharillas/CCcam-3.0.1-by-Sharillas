static int via_get_key(uint8_t *buf, uint32_t ident, char key_name,
                       uint32_t key_index, uint32_t key_length) {
    char key_str[4];
    snprintf(key_str, sizeof(key_str), "%c%X", key_name, (unsigned int)key_index);

    if (cccam_emu_find_key('F', ident, key_str, 0, buf, key_length) >= (int)key_length) return 1;
    if (cccam_emu_find_key('I', ident, key_str, 0, buf, key_length) >= (int)key_length) return 1;
    if (cccam_emu_find_key('T', ident, key_str, 0, buf, key_length) >= (int)key_length) return 1;

    // TNT SAT / CSAT: o identificador 0xD00040 usa as chaves do 0x030B00
    if (ident == 0xD00040) {
        if (cccam_emu_find_key('F', 0x030B00, key_str, 0, buf, key_length) >= (int)key_length) return 1;
        if (cccam_emu_find_key('I', 0x030B00, key_str, 0, buf, key_length) >= (int)key_length) return 1;
        if (cccam_emu_find_key('T', 0x030B00, key_str, 0, buf, key_length) >= (int)key_length) return 1;
    }

    return 0;
}

// --- Via 1 ---

static void via1_mod(const uint8_t *key2, uint8_t *data)
{
	int32_t kb, db;

	for (db = 7; db >= 0; db--)
	{
		for (kb = 7; kb > 3; kb--)
		{
			int32_t a0 = kb ^ db;
			int32_t pos = 7;

			if (a0 & 4)
			{
				a0 ^= 7;
				pos ^= 7;
			}

			a0 = (a0 ^ (kb & 3)) + (kb & 3);

			if (!(a0 & 4))
			{
				data[db] ^= (key2[kb] ^ ((data[kb ^ pos] * key2[kb ^ 4]) & 0xFF));
			}
		}
	}

	for (db = 0; db < 8; db++)
	{
		for (kb = 0; kb < 4; kb++)
		{
			int32_t a0 = kb ^ db;
			int32_t pos = 7;

			if (a0 & 4)
			{
				a0 ^= 7;
				pos ^= 7;
			}

			a0 = (a0 ^ (kb & 3)) + (kb & 3);

			if (!(a0 & 4))
			{
				data[db] ^= (key2[kb] ^ ((data[kb ^ pos] * key2[kb ^ 4]) & 0xFF));
			}
		}
	}
}

static void via1_decode(uint8_t *data, uint8_t *key)
{
	via1_mod(key + 8, data);
	cccam_emu_nc_des(key, NC_DES_ECM_CRYPT, data);
	via1_mod(key + 8, data);
}

static void via1_hash(uint8_t *data, uint8_t *key)
{
	via1_mod(key + 8, data);
	cccam_emu_nc_des(key, NC_DES_ECM_HASH, data);
	via1_mod(key + 8, data);
}

static inline void via1_do_hash(uint8_t *hashbuffer, uint8_t *pH, uint8_t data, uint8_t *hashkey)
{
	hashbuffer[*pH] ^= data;
	(*pH)++;

	if (*pH == 8)
	{
		via1_hash(hashbuffer, hashkey);
		*pH = 0;
	}
}

